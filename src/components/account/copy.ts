export type AccountCopy = (typeof ACCOUNT_COPY)[Locale];

export function numberLocale(locale: Locale) {
  return locale === "de" ? "de-DE" : locale === "tr" ? "tr-TR" : "en-GB";
}

export function formatMoney(amount: number, currency: string, locale: Locale) {
  return displayMoney(amount, currency, locale);
}

export function formatDate(value: string | null | undefined, locale: Locale) {
  if (!value) return "—";
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return "—";
  return new Intl.DateTimeFormat(numberLocale(locale), { dateStyle: "medium" }).format(date);
}
